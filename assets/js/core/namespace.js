/* ==========================================================================
   运行时命名空间
   为其余模块提供四个共享容器，替代原先单一闭包中的隐式作用域。
   --------------------------------------------------------------------------
   M  DRM.meta   只读常量：类元信息、关系分组、公理映射
   D  DRM.data   一次装配的数据模型：节点、边、索引、推理结果
   S  DRM.state  可写运行时状态：相机、筛选、选中、临时开关
   api DRM.api   跨模块公开函数：由各模块在加载结束时挂载
   --------------------------------------------------------------------------
   约定：除文件内私有函数外，跨模块引用一律写成 api.xxx / S.xxx / D.xxx / M.xxx，
        便于检索依赖，也让加载顺序一目了然（见 index.html 中的 script 顺序）。
   文件：assets/js/core/namespace.js
   ========================================================================== */
(function (global) {
  'use strict';

  var DRM = global.DRM = global.DRM || {};
  DRM.meta = DRM.meta || {};
  DRM.data = DRM.data || {};
  DRM.state = DRM.state || {};
  DRM.api = DRM.api || {};

  /* 版本信息，便于在控制台确认脚本是否全部就位 */
  DRM.version = '2.0.0-modular';
})(window);
